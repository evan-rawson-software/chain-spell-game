"""Build public/music from the local asset library (C:\Projects\assets).

Run:  python -I tools/build-music.py      (needs numpy + scipy)

Source: Mini Music Pack Dark Fantasy by TKIMUSE (purchased; licensed to the project author, not
redistributable as a raw library). The pack ships 48 kHz / 24-bit stereo WAV stems (L1..Ln play
together); we sum the stems of each loop file (the pack's own loop, unmodified in length), downmix
to mono, resample to 22.05 kHz, normalize to about -3 dBFS and write 16-bit WAV. Also writes CREDITS.md.
"""
import os
import wave

import numpy as np
from scipy.signal import resample_poly

ASSETS = r"C:\Projects\assets"
PACK = "minimusicpackdarkfantasy/Mini Music Pack Dark Fantasy by TKIMUSE/Music Assets"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "public", "music")
RATE = 22050
PEAK = 10 ** (-3 / 20)
LIC = "Purchased, royalty-free (TKIMUSE); stems mixed, converted to mono 22.05 kHz"

TRACKS = [
    ("title", ["Field Tension/Mx_Fantasy_Field_Tension_Loop_L%d_142BPM_13.wav" % i for i in (1, 2, 3)]),
    ("map", ["Exploration/Mx_Fantasy_Explore_Loop_81BPM_125.wav"]),
    ("battle", ["Field Battle/Mx_Fantasy_Field_Battle_Loop_L%d_142BPM_53.wav" % i for i in (1, 2, 3, 4)]),
    ("boss", ["Boss Battle/Mx_Fantasy_Boss_Battle_Loop_L%d_131BPM_87.wav" % i for i in (1, 2, 3, 4, 5)]),
]


def read_mono(path):
    with wave.open(path, "rb") as w:
        ch, sw, sr, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    assert sw == 3 and sr == 48000, (sw, sr)
    b = np.frombuffer(raw, dtype=np.uint8).reshape(-1, 3).astype(np.int32)
    v = b[:, 0] | (b[:, 1] << 8) | (b[:, 2] << 16)
    v = np.where(v & 0x800000, v - (1 << 24), v).astype(np.float64) / 8388608.0
    return v.reshape(-1, ch).mean(axis=1)


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith(".wav"):
            os.remove(os.path.join(OUT, f))
    credits, total = [], 0
    for name, files in TRACKS:
        mix = None
        for rel in files:
            m = read_mono(os.path.join(ASSETS, PACK, rel))
            mix = m if mix is None else mix[:len(m)] + m[:len(mix)]
        out = resample_poly(mix, 147, 320)  # 48000 -> 22050
        out *= PEAK / (np.abs(out).max() or 1.0)
        pcm = np.round(out * 32767).astype("<i2")
        dst = os.path.join(OUT, name + ".wav")
        with wave.open(dst, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes(pcm.tobytes())
        size = os.path.getsize(dst)
        total += size
        print("%s.wav  %.1f s  %.2f MB" % (name, len(pcm) / RATE, size / 1e6))
        credits.append((name + ".wav", "minimusicpackdarkfantasy",
                        " + ".join(os.path.basename(f) for f in files), LIC))
    with open(os.path.join(OUT, "CREDITS.md"), "w", encoding="utf-8") as f:
        f.write("# Music credits\n\nGenerated by `tools/build-music.py`. All loops are from Mini Music Pack "
                "Dark Fantasy by TKIMUSE, licensed to the project author; they are game assets (stems "
                "mixed, mono, 22.05 kHz), not a redistributable library.\n\n"
                "| File | Source pack | Original file(s) | License |\n|---|---|---|---|\n")
        for c in credits:
            f.write("| %s | %s | %s | %s |\n" % c)
    print("total %.2f MB" % (total / 1e6))


main()
